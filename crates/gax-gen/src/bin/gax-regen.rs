//! Regenerate the standard algebras shipped in the `gax` crate.
//!
//! Usage: `cargo run -p gax-gen --bin gax-regen [--check] [--verbose]`.
//! With `--check`, nothing is written and the exit code is nonzero when a committed file
//! differs from what the generator produces (used in CI).

use gax_gen::emit::{Config, emit, emit_tests};
use gax_gen::emit_laws::{emit_law_tests, factor_table, laws};
use gax_gen::spec::AlgebraSpec;
use std::path::Path;
use std::process::ExitCode;

#[allow(clippy::too_many_lines)]
fn main() -> ExitCode {
    let check = std::env::args().any(|a| a == "--check");
    let verbose = std::env::args().any(|a| a == "--verbose");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../gax");
    let mut specs: Vec<_> = std::fs::read_dir(root.join("specs"))
        .expect("specs directory")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "gax"))
        .collect();
    specs.sort();
    // Test-only algebras (declared with `algebra!` in the tests): only their law suites.
    let mut test_specs: Vec<_> = std::fs::read_dir(root.join("tests/specs"))
        .expect("tests/specs directory")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "gax"))
        .collect();
    test_specs.sort();
    let mut stale = false;
    let mut tables = String::from(
        "<!-- @generated by gax-regen. Do not edit by hand. -->\n\n# Versor law factors\n\n\
         The factor `f` in each versor law, per algebra, derived by the generator from its exact\n\
         tables (modulo the conditions that make `m` a versor: the non-scalar parts of `m ~m`\n\
         vanish) and checked against the generated code by `tests/laws_*.rs`. `‖m‖²` is the\n\
         scalar part of `m ~m`; for a `Unit` versor every factor is `±1`. See [laws.md](laws.md).\n\n",
    );
    for path in test_specs {
        let src = std::fs::read_to_string(&path).expect("read spec");
        let spec = match AlgebraSpec::parse(&src) {
            Ok(s) => s,
            Err(e) => {
                eprintln!("{}: {e}", path.display());
                return ExitCode::FAILURE;
            }
        };
        let (_, stats) = emit(
            &spec,
            &Config {
                core: "::gax".into(),
                batch: None,
                check_units: None,
            },
        );
        let l = laws(&spec, &stats);
        let prelude = format!("gax::algebra! {{\n{src}}}\n\nuse {}::*;", spec.name);
        let target = root.join("tests").join(format!("laws_{}.rs", spec.name));
        stale |= write_or_check(
            &target,
            &emit_law_tests(&spec, &l, "#![cfg(feature = \"macros\")]", &prelude),
            check,
        );
        tables.push_str(&factor_table(&spec, &l));
    }
    for path in specs {
        let src = std::fs::read_to_string(&path).expect("read spec");
        let spec = match AlgebraSpec::parse(&src) {
            Ok(s) => s,
            Err(e) => {
                eprintln!("{}: {e}", path.display());
                return ExitCode::FAILURE;
            }
        };
        let (code, stats) = emit(
            &spec,
            &Config {
                core: "crate".into(),
                batch: Some("#[cfg(feature = \"batch\")]".into()),
                check_units: Some("#[cfg(feature = \"check-units\")]".into()),
            },
        );
        let tests = emit_tests(
            &spec,
            &stats,
            &format!("gax::{}", spec.name),
            &format!("../specs/{}.gax", spec.name),
        );
        let test_target = root.join("tests").join(format!("ops_{}.rs", spec.name));
        stale |= write_or_check(&test_target, &tests, check);
        let l = laws(&spec, &stats);
        let law_target = root.join("tests").join(format!("laws_{}.rs", spec.name));
        stale |= write_or_check(
            &law_target,
            &emit_law_tests(
                &spec,
                &l,
                &format!("#![cfg(feature = \"{}\")]", spec.name),
                &format!("use gax::{}::*;", spec.name),
            ),
            check,
        );
        tables.push_str(&factor_table(&spec, &l));
        let target = root.join("src/algebras").join(format!("{}.rs", spec.name));
        stale |= write_or_check(&target, &code, check);
        eprintln!(
            "{}: {} lines, {} product impls, {} sandwich kernels",
            spec.name,
            code.lines().count(),
            stats.binary_impls,
            stats.sandwich_impls
        );
        if verbose {
            for (v, x, unit, cost) in &stats.sandwich_costs {
                eprintln!("    {}{v} >> {x}: {cost}", if *unit { "Unit " } else { "" });
            }
        }
    }
    stale |= write_or_check(&root.join("../../docs/law-factors.md"), &tables, check);
    if stale {
        ExitCode::FAILURE
    } else {
        ExitCode::SUCCESS
    }
}

fn write_or_check(target: &Path, content: &str, check: bool) -> bool {
    let current = std::fs::read_to_string(target).unwrap_or_default();
    if current == content {
        return false;
    }
    if check {
        eprintln!("{} is out of date", target.display());
        true
    } else {
        std::fs::write(target, content).expect("write generated file");
        false
    }
}
