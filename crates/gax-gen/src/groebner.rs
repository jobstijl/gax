//! Gröbner bases and normal forms (Buchberger's algorithm, graded reverse lexicographic order).
//!
//! Type conditions (`x ~x = 1`) and atom identities (`s² = x` for `s = √x`, `r x = 1` for
//! `r = 1/x`) generate an ideal. The normal form of a polynomial modulo a Gröbner basis of
//! that ideal is canonical, so two expressions are equal under the conditions exactly when
//! their difference has normal form zero. The simplifier uses this to verify every
//! simplification, and as one of the reduction strategies it compares.

use crate::poly::{Monomial, Poly, Rational};
use std::cmp::Ordering;

/// Graded reverse lexicographic comparison of monomials (variables ordered by index).
pub fn grevlex(a: &Monomial, b: &Monomial) -> Ordering {
    a.degree().cmp(&b.degree()).then_with(|| {
        // Compare exponent vectors from the last variable; the one with the smaller exponent
        // in the last differing variable is larger.
        let vars: std::collections::BTreeSet<u32> = a.0.iter().chain(&b.0).copied().collect();
        for &v in vars.iter().rev() {
            let (ea, eb) = (a.power(v), b.power(v));
            if ea != eb {
                return eb.cmp(&ea);
            }
        }
        Ordering::Equal
    })
}

/// Leading monomial and coefficient.
pub fn leading(p: &Poly) -> Option<(Monomial, Rational)> {
    p.0.iter()
        .max_by(|x, y| grevlex(x.0, y.0))
        .map(|(m, c)| (m.clone(), *c))
}

fn lcm(a: &Monomial, b: &Monomial) -> Monomial {
    let mut out = Vec::new();
    let vars: std::collections::BTreeSet<u32> = a.0.iter().chain(&b.0).copied().collect();
    for v in vars {
        for _ in 0..a.power(v).max(b.power(v)) {
            out.push(v);
        }
    }
    Monomial(out)
}

fn times(p: &Poly, m: &Monomial, c: Rational) -> Poly {
    let mut out = Poly::zero();
    for (pm, pc) in &p.0 {
        out.add_term(pm.mul(m), *pc * c);
    }
    out
}

/// Full normal form of `p` modulo the polynomials in `basis`.
pub fn normal_form(p: &Poly, basis: &[Poly]) -> Poly {
    let leads: Vec<(Monomial, Rational)> = basis.iter().filter_map(leading).collect();
    let mut p = p.clone();
    let mut rem = Poly::zero();
    while let Some((m, c)) = leading(&p) {
        let mut reduced = false;
        for (g, (lm, lc)) in basis.iter().zip(&leads) {
            if let Some(q) = m.div(lm) {
                p = &p - &times(g, &q, c * lc.recip());
                reduced = true;
                break;
            }
        }
        if !reduced {
            rem.add_term(m.clone(), c);
            p.add_term(m, -c);
        }
    }
    rem
}

/// A reduced Gröbner basis of the ideal generated by `gens`. Returns `None` if the
/// computation exceeds `max_pairs` S-polynomials.
pub fn groebner(gens: &[Poly], max_pairs: usize) -> Option<Vec<Poly>> {
    let mut g: Vec<Poly> = gens.iter().filter(|p| !p.is_zero()).map(monic).collect();
    let mut pairs: Vec<(usize, usize)> = (0..g.len())
        .flat_map(|i| (0..i).map(move |j| (j, i)))
        .collect();
    let mut processed = 0;
    while let Some((i, j)) = pairs.pop() {
        processed += 1;
        if processed > max_pairs {
            return None;
        }
        let (li, _) = leading(&g[i])?;
        let (lj, _) = leading(&g[j])?;
        // Buchberger's first criterion: coprime leading monomials give a zero remainder.
        if lcm(&li, &lj).degree() == li.degree() + lj.degree() {
            continue;
        }
        let l = lcm(&li, &lj);
        let s =
            &times(&g[i], &l.div(&li)?, Rational::ONE) - &times(&g[j], &l.div(&lj)?, Rational::ONE);
        let r = normal_form(&s, &g);
        if !r.is_zero() {
            g.push(monic(&r));
            let n = g.len() - 1;
            pairs.extend((0..n).map(|k| (k, n)));
        }
    }
    // Reduce: drop elements whose leading monomial is divisible by another's, then
    // inter-reduce the rest.
    let mut keep: Vec<Poly> = Vec::new();
    for (i, p) in g.iter().enumerate() {
        let (lp, _) = leading(p)?;
        let redundant = g.iter().enumerate().any(|(j, q)| {
            j != i && leading(q).is_some_and(|(lq, _)| lp.div(&lq).is_some() && (lq != lp || j < i))
        });
        if !redundant {
            keep.push(p.clone());
        }
    }
    let reduced: Vec<Poly> = (0..keep.len())
        .map(|i| {
            let others: Vec<Poly> = keep
                .iter()
                .enumerate()
                .filter(|(j, _)| *j != i)
                .map(|(_, p)| p.clone())
                .collect();
            let (lm, lc) = leading(&keep[i]).expect("nonzero");
            let tail = &keep[i] - &Poly::term(lm.clone(), lc);
            &Poly::term(lm, Rational::ONE) + &normal_form(&tail.scale(lc.recip()), &others)
        })
        .collect();
    Some(reduced)
}

fn monic(p: &Poly) -> Poly {
    let (_, c) = leading(p).expect("nonzero");
    p.scale(c.recip())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unit_rotor_ideal() {
        let v = Poly::var;
        let one = Poly::constant(Rational::ONE);
        // a² + b² = 1
        let r = &(&(&v(0) * &v(0)) + &(&v(1) * &v(1))) - &one;
        let g = groebner(&[r], 100).unwrap();
        // a⁴ + 2a²b² + b⁴ = 1 under the condition
        let a2 = &v(0) * &v(0);
        let b2 = &v(1) * &v(1);
        let p = &(&(&a2 * &a2) + &(&a2 * &b2).scale(Rational::int(2))) + &(&b2 * &b2);
        assert_eq!(normal_form(&(&p - &one), &g), Poly::zero());
        assert_ne!(normal_form(&(&a2 - &one), &g), Poly::zero());
    }

    #[test]
    fn two_generators() {
        let v = Poly::var;
        // x y - 1, y² - x  (y = sqrt(x), x y = 1)
        let g = groebner(
            &[
                &(&v(0) * &v(1)) - &Poly::constant(Rational::ONE),
                &(&v(1) * &v(1)) - &v(0),
            ],
            100,
        )
        .unwrap();
        // then y³ = x y = 1
        let y3 = &(&v(1) * &v(1)) * &v(1);
        assert_eq!(
            normal_form(&(&y3 - &Poly::constant(Rational::ONE)), &g),
            Poly::zero()
        );
    }
}
