//! numga's `twistors/scenarios.py`: the Robinson congruence's flow lines at time zero, the
//! Hopfion's field lines carried along its rays, and a light ray recovered from its twistor
//! through two events, at rest and boosted.

use crate::twistors::{
    B, Even, Event, Spatial, Twistor, across, act, at_time, cl42, event, event_of, helicity,
    moved_point, moved_spatial, point, ray, symmetry, through, time, time_of, x, y, z,
};

/// A Hopf fibre on a torus: the circle the rotor `start exp(symmetry helicity phase)` traces in
/// the stereographic projection of the unit rotors onto space, its plane of turning made a
/// patch of space by the helicity and joined across time, `(B helicity / (1 + s)) ∨ t u v` for
/// the rotor `s + B`, sampled at `samples + 1` phases from `-π` to `π` (both ends, the same
/// point).
pub fn fibre(polar: f64, azimuth: f64, samples: usize) -> Vec<Spatial> {
    let start =
        (B::from(z() ^ x()) * (-azimuth / 2.0)).exp() * (B::from(x() ^ y()) * (polar / 2.0)).exp();
    let generator = (symmetry() * helicity()).cast::<cl42::Bivector>();
    (0..=samples)
        .map(|k| {
            let phase = -core::f64::consts::PI + core::f64::consts::TAU * k as f64 / samples as f64;
            let rotor = (start * (generator * phase).exp()).into_inner();
            let patch = rotor.grade::<2>() * helicity() * (1.0 / (1.0 + rotor.s()));
            (patch ^ across()).cast::<cl42::Spatial>()
        })
        .collect()
}

/// Linked circles tangent to the Robinson directions at time zero: `per_circle` fibres at
/// each polar angle, on nested tori.
pub fn fibres(polars: &[f64], per_circle: usize, samples: usize) -> Vec<Vec<Spatial>> {
    polars
        .iter()
        .flat_map(|polar| {
            (0..per_circle).map(move |k| {
                let azimuth = core::f64::consts::TAU * k as f64 / per_circle as f64;
                fibre(*polar, azimuth, samples)
            })
        })
        .collect()
}

/// The congruence's flow lines shown: polar angles, fibres per angle and samples per fibre.
pub const POLARS: [f64; 3] = [
    0.5 * core::f64::consts::PI,
    0.65 * core::f64::consts::PI,
    0.8 * core::f64::consts::PI,
];
pub const PER_CIRCLE: usize = 10;
pub const FIBRE_SAMPLES: usize = 240;

/// The turn of space from the flow lines to the Hopfion's electric lines, a quarter turn in
/// the `xy` plane.
pub fn electric_turn() -> Even {
    (B::from(x() ^ y()) * core::f64::consts::FRAC_PI_4)
        .exp()
        .into_inner()
}

/// The turn from the flow lines to the magnetic lines, a quarter turn in the `yz` plane.
#[cfg_attr(not(test), allow(dead_code))] // the tests follow the magnetic lines too
pub fn magnetic_turn() -> Even {
    (B::from(y() ^ z()) * core::f64::consts::FRAC_PI_4)
        .exp()
        .into_inner()
}

/// Curves of space turned by a rotor.
pub fn turned(curves: &[Vec<Spatial>], r: Even) -> Vec<Vec<Spatial>> {
    curves
        .iter()
        .map(|c| c.iter().map(|p| moved_spatial(r, *p)).collect())
        .collect()
}

/// The rapidities of the boosts that carry the incidence along, the first at rest.
pub const RAPIDITIES: [f64; 2] = [0.0, 0.8];

/// A boost along `x` by a rapidity: generated by the dual of the plane `x* ∨ T` through the
/// events along `x` and along time.
pub fn boost(rapidity: f64) -> Even {
    let plane = (x().hodge() & time().cast::<cl42::Point>()).hodge();
    (plane.cast::<cl42::Bivector>() * (rapidity / 2.0))
        .exp()
        .into_inner()
}

/// The twistor of the light ray through two null-separated events, carried by each boost:
/// per boost, its twistor, the two events, and samples of the reconstructed ray.
pub struct Incidence {
    #[cfg_attr(not(test), allow(dead_code))] // the tests check the ray against it
    pub twistor: Twistor,
    pub events: [Event; 2],
    pub ray: Vec<Event>,
}

/// The incidence at rest and boosted. The boost acts on the twistor by its representation
/// and on the events by the sandwich.
pub fn incidence() -> Vec<Incidence> {
    let emission = event(-0.6, 0.0, 0.3, 0.0);
    let light = time() + event(1.0, 0.0, 1.0, 0.0) * core::f64::consts::FRAC_1_SQRT_2;
    let events = [emission, emission + light * 1.4];
    let points = events.map(point);
    let twistor = through(points[0], points[1]);
    // The ray is sampled this far beyond the two events, as a share of their separation.
    let (margin, samples) = (0.6, 120);
    RAPIDITIES
        .iter()
        .map(|r| {
            let b = boost(*r);
            let twistor = act(b, twistor);
            let light = ray(twistor, twistor);
            let events = points.map(|p| event_of(moved_point(b, p)));
            let times = events.map(time_of);
            let ray = (0..samples)
                .map(|k| {
                    let share = -margin + (1.0 + 2.0 * margin) * k as f64 / (samples - 1) as f64;
                    at_time(light, times[0] + (times[1] - times[0]) * share)
                })
                .collect();
            Incidence {
                twistor,
                events,
                ray,
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::twistors::tests::{TOLERANCE, vanishes};
    use crate::twistors::{
        ExtrinsicTwistor, Faraday, at, coordinates, flux, hopfion, incidence as incident, robinson,
        spacetime_volume, spatial, t, temporal,
    };
    use gax::ApproxEq;

    /// Centred differences of sampled curves resolve their tangents to about this accuracy.
    const TANGENT_TOLERANCE: f64 = 0.003;
    /// The flow lines the tests sample: polar angles, fibres per angle, samples per fibre.
    const TEST_POLARS: [f64; 2] = [0.4 * core::f64::consts::PI, 0.65 * core::f64::consts::PI];
    const TEST_PER_CIRCLE: usize = 3;
    const TEST_SAMPLES: usize = 192;

    /// numga's test: the sampled circles run along the spatial directions of the congruence,
    /// their unit centred differences joined with the flow vanishing.
    #[test]
    fn flow_lines_follow_the_robinson_directions() {
        for curve in fibres(&TEST_POLARS, TEST_PER_CIRCLE, TEST_SAMPLES) {
            for i in 1..curve.len() - 1 {
                let tangent = (curve[i + 1] - curve[i - 1]).normalized();
                let flow = spatial(robinson(at(curve[i], 0.0)));
                let joined = tangent & flow;
                assert!(vanishes(joined, joined * 0.0, TANGENT_TOLERANCE));
            }
        }
    }

    /// numga's test: after their material points have followed the straight energy-flow rays,
    /// the electric and the magnetic lines still run along their fields: the plane each line's
    /// unit step sweeps through time, the dual of `step ∨ T`, commutes with the field's part
    /// through time (the magnetic part turned into time by the spacetime volume).
    #[test]
    fn field_lines_follow_their_fields_along_the_energy_flow_rays() {
        type Reading = fn(Faraday) -> Faraday;
        let curves = fibres(&TEST_POLARS, TEST_PER_CIRCLE, TEST_SAMPLES);
        let electric: Reading = |f| temporal(f);
        let magnetic: Reading = |f| temporal(spacetime_volume() * f);
        let kinds = [
            (turned(&curves, electric_turn()), electric),
            (turned(&curves, magnetic_turn()), magnetic),
        ];
        for instant in [-0.8, 0.0, 0.8] {
            for (lines, part) in &kinds {
                for curve in lines {
                    let events: Vec<Event> = curve
                        .iter()
                        .map(|p| at(*p, 0.0) + robinson(at(*p, 0.0)) * instant)
                        .collect();
                    for i in 1..events.len() - 1 {
                        let step = (events[i + 1] - events[i - 1]).normalized();
                        let sweep = (step & time()).hodge().cast::<cl42::Bivector>();
                        let field = part(hopfion(events[i]));
                        let field = field.normalized();
                        let commutator = sweep.commutator(B::from(field));
                        assert!(vanishes(commutator, commutator * 0.0, TANGENT_TOLERANCE));
                    }
                }
            }
        }
    }

    /// numga's test: the Gauss integral counts one linking of two distinct closed fibres, the
    /// volume the three directions span read by the volume of space, `x y z ∨ (o ∨ a ∨ b)`.
    #[test]
    fn two_fibres_link_once() {
        let curves = fibres(&TEST_POLARS, TEST_PER_CIRCLE, TEST_SAMPLES);
        let space = (x() ^ y() ^ z()).cast::<cl42::Multivector>();
        let (first, second) = (&curves[0], &curves[1]);
        let mut sum = 0.0;
        for a in first.windows(2) {
            for b in second.windows(2) {
                let offset = (a[1] + a[0] - b[1] - b[0]) * 0.5;
                let spanned = offset & (a[1] - a[0]) & (b[1] - b[0]);
                let volume = (space & spanned.cast::<cl42::Multivector>()).s();
                sum += volume / coordinates(offset).norm().powi(3);
            }
        }
        let linking = sum / (4.0 * core::f64::consts::PI);
        assert!((linking.abs() - 1.0).abs() < 1e-4, "{linking}");
    }

    /// numga's test: a ray's intersection with a time slice reconstructs the incident events,
    /// also when a boost changes their times, and every sampled ray event sends its twistor to
    /// zero.
    #[test]
    fn incidence_rays_meet_their_events_at_rest_and_boosted() {
        for case in incidence() {
            let light = ray(case.twistor, case.twistor);
            for e in case.events {
                assert!(at_time(light, time_of(e)).max_abs_diff(&e) < TOLERANCE);
            }
            for r in &case.ray {
                let sent = incident(point(*r).cast::<cl42::Multivector>(), case.twistor);
                assert!(vanishes(sent, ExtrinsicTwistor::zero(), TOLERANCE));
            }
        }
    }

    /// numga's scenario checks: the Hopfion is null, and its energy flows along the Robinson
    /// ray through each point of its electric lines: its flux along time at unit time.
    #[test]
    fn hopfion_is_null_and_flows_along_the_robinson_rays() {
        let lines = turned(&fibres(&POLARS, PER_CIRCLE, FIBRE_SAMPLES), electric_turn());
        for p in lines.iter().flatten() {
            let e = at(*p, 0.0);
            let field = hopfion(e);
            let flux = flux(field);
            assert!(vanishes(field * field, Even::zero(), 1e-12));
            assert!((flux * (1.0 / time_of(flux))).max_abs_diff(&robinson(e)) < 1e-10);
        }
    }

    /// Points of two fibres, the boost, and the events at rest and boosted, against numga's
    /// numbers.
    #[test]
    fn scenes_match_numga() {
        let pi = core::f64::consts::PI;
        let curves = fibres(&[0.5 * pi, 0.8 * pi], 10, 240);
        let expected = [
            (3, 0, [-0.97893185, 0.97893185, -0.71123562]),
            (3, 60, [-0.97123031, -0.97123031, 1.33678384]),
            (3, 120, [0.40410463, -0.40410463, 0.2935992]),
            (17, 30, [-0.15633541, 0.32071619, 0.98706295]),
            (17, 90, [1.35199238, -0.06957654, 0.21413456]),
        ];
        for (curve, sample, [px, py, pz]) in expected {
            let p = coordinates(curves[curve][sample]);
            assert!(
                (p - gax::vga3d::Vector::new(px, py, pz)).norm() < 1e-7,
                "{p:?}"
            );
        }
        let b = boost(0.8);
        let want = Even::from(cl42::Scalar::new(1.0810723718384547))
            + Even::from(B::from(x() ^ t()) * -0.41075232580281534);
        assert!(b.max_abs_diff(&want) < 1e-15);
        let cases = incidence();
        let want = [
            [
                event(-0.6, 0.0, 0.3, 0.0),
                event(0.3899494936611664, 0.0, 1.2899494936611664, 1.4),
            ],
            [
                event(-0.8024609677829064, 0.0, 0.3, 0.5328635893125735),
                event(
                    -0.7218162949463484,
                    0.0,
                    1.2899494936611664,
                    1.526092446755266,
                ),
            ],
        ];
        for (case, want) in cases.iter().zip(want) {
            for (e, w) in case.events.iter().zip(want) {
                assert!(e.max_abs_diff(&w) < 1e-14, "{e:?}");
            }
        }
    }
}
