//! A stroke vector font in the arcade tradition: every glyph is a few polylines on a 4 x 6 grid
//! (y up). From the warp example of this repository.

/// The strokes of a glyph (points on the 4 x 6 grid), or `None` for characters it lacks.
fn glyph(c: char) -> Option<&'static [&'static [(f32, f32)]]> {
    Some(match c.to_ascii_uppercase() {
        'A' => &[
            &[(0., 0.), (0., 4.), (2., 6.), (4., 4.), (4., 0.)],
            &[(0., 3.), (4., 3.)],
        ],
        'B' => &[
            &[
                (0., 0.),
                (0., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (3., 3.),
                (0., 3.),
            ],
            &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)],
        ],
        'C' => &[&[(4., 0.), (0., 0.), (0., 6.), (4., 6.)]],
        'D' => &[&[
            (0., 0.),
            (0., 6.),
            (2., 6.),
            (4., 4.),
            (4., 2.),
            (2., 0.),
            (0., 0.),
        ]],
        'E' => &[
            &[(4., 0.), (0., 0.), (0., 6.), (4., 6.)],
            &[(0., 3.), (3., 3.)],
        ],
        'F' => &[&[(0., 0.), (0., 6.), (4., 6.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[
            (2.5, 2.5),
            (4., 2.5),
            (4., 0.),
            (0., 0.),
            (0., 6.),
            (4., 6.),
            (4., 4.5),
        ]],
        'H' => &[
            &[(0., 0.), (0., 6.)],
            &[(4., 0.), (4., 6.)],
            &[(0., 3.), (4., 3.)],
        ],
        'I' => &[
            &[(0., 0.), (4., 0.)],
            &[(2., 0.), (2., 6.)],
            &[(0., 6.), (4., 6.)],
        ],
        'J' => &[&[(0., 1.5), (1., 0.), (3., 0.), (4., 1.), (4., 6.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 6.), (0., 3.), (4., 0.)]],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.5), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'O' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)]],
        'P' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.)]],
        'Q' => &[
            &[(0., 0.), (0., 6.), (4., 6.), (4., 2.), (2., 0.), (0., 0.)],
            &[(2.2, 2.2), (4., 0.)],
        ],
        'R' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.), (4., 0.)]],
        'S' => &[&[(4., 6.), (0., 6.), (0., 3.), (4., 3.), (4., 0.), (0., 0.)]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 0.), (4., 0.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (0., 0.), (2., 2.5), (4., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        '0' => &[
            &[(0., 0.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)],
            &[(4., 6.), (0., 0.)],
        ],
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        '2' => &[&[(0., 6.), (4., 6.), (4., 3.), (0., 3.), (0., 0.), (4., 0.)]],
        '3' => &[
            &[(0., 6.), (4., 6.), (4., 0.), (0., 0.)],
            &[(1., 3.), (4., 3.)],
        ],
        '4' => &[&[(0., 6.), (0., 3.), (4., 3.)], &[(4., 6.), (4., 0.)]],
        '5' => &[&[(4., 6.), (0., 6.), (0., 3.), (4., 3.), (4., 0.), (0., 0.)]],
        '6' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (0., 3.)]],
        '7' => &[&[(0., 6.), (4., 6.), (4., 0.)]],
        '8' => &[
            &[(0., 0.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)],
            &[(0., 3.), (4., 3.)],
        ],
        '9' => &[&[(4., 3.), (0., 3.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)]],
        '.' => &[&[(2., 0.), (2., 0.4)]],
        ',' => &[&[(2., 0.4), (1.5, -0.8)]],
        ':' => &[&[(2., 1.), (2., 1.4)], &[(2., 4.), (2., 4.4)]],
        '-' => &[&[(1., 3.), (3., 3.)]],
        '+' => &[&[(1., 3.), (3., 3.)], &[(2., 2.), (2., 4.)]],
        '*' => &[&[(1., 2.), (3., 4.)], &[(1., 4.), (3., 2.)]],
        '!' => &[&[(2., 6.), (2., 2.)], &[(2., 0.), (2., 0.4)]],
        '?' => &[
            &[
                (0., 5.),
                (1., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (2., 3.),
                (2., 2.),
            ],
            &[(2., 0.), (2., 0.4)],
        ],
        '/' => &[&[(0., 0.), (4., 6.)]],
        '|' => &[&[(2., -0.5), (2., 6.5)]],
        '_' => &[&[(0., -0.5), (4., -0.5)]],
        '\'' => &[&[(2., 6.), (2., 4.8)]],
        '(' => &[&[(3., 6.), (2., 5.), (2., 1.), (3., 0.)]],
        ')' => &[&[(1., 6.), (2., 5.), (2., 1.), (1., 0.)]],
        '<' => &[&[(3., 5.), (1., 3.), (3., 1.)]],
        '>' => &[&[(1., 5.), (3., 3.), (1., 1.)]],
        '=' => &[&[(1., 2.), (3., 2.)], &[(1., 4.), (3., 4.)]],
        '%' => &[
            &[(0., 0.), (4., 6.)],
            &[(0., 6.), (1., 6.), (1., 5.), (0., 5.), (0., 6.)],
            &[(3., 1.), (4., 1.), (4., 0.), (3., 0.), (3., 1.)],
        ],
        ' ' => &[],
        _ => return None,
    })
}

/// Horizontal alignment.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Align {
    /// From the left edge.
    Left,
    /// Centred.
    Center,
    /// To the right edge.
    Right,
}

/// The width of `s` at glyph height `size`.
pub fn width(s: &str, size: f32) -> f32 {
    let n = s.chars().count() as f32;
    if n == 0.0 {
        0.0
    } else {
        (n * 6.0 - 2.0) * size / 6.0
    }
}

/// The segments of `s` with its baseline at `(x, y)` and glyphs `size` tall, as
/// `[x0, y0, x1, y1]`.
pub fn segments(s: &str, x: f32, y: f32, size: f32, align: Align) -> Vec<[f32; 4]> {
    let k = size / 6.0;
    let w = width(s, size);
    let x0 = match align {
        Align::Left => x,
        Align::Center => x - w * 0.5,
        Align::Right => x - w,
    };
    let mut out = Vec::new();
    for (i, c) in s.chars().enumerate() {
        let gx = x0 + i as f32 * 6.0 * k;
        let strokes = glyph(c).or_else(|| glyph('?')).unwrap_or(&[]);
        for stroke in strokes {
            for pair in stroke.windows(2) {
                let (a, b) = (pair[0], pair[1]);
                out.push([gx + a.0 * k, y + a.1 * k, gx + b.0 * k, y + b.1 * k]);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_glyph_exists() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:-+*!?/'()<>=% ".chars() {
            assert!(glyph(c).is_some(), "{c}");
        }
        let s = segments("WARP 2x", 0.0, 0.0, 6.0, Align::Center);
        assert!(s.len() > 15);
        assert!((width("AB", 6.0) - 10.0).abs() < 1e-6);
    }
}
