"""Export numga results as fixtures for gax's cross-check.

For PGA2D and PGA3D, random full multivectors are combined with numga's operators, and
inputs and outputs are written as dense coefficient vectors in gax's canonical blade order:
bit i of the mask is gax basis vector e_i, with e0 the degenerate direction (numga's `w`).
"""
import numpy as np
from numga.algebras import PGA2D, PGA3D
from numga import NumpyContext

def mapping(n_euclid):
    # numga bits: x=0, y=1, (z=2), w=last. gax bits: e0=0 (w), e1=1 (x), ...
    n = n_euclid + 1
    def to_gax(mask):
        factors = [i for i in range(n) if mask & (1 << i)]            # numga order
        gax_index = [(i + 1 if i < n_euclid else 0) for i in factors]  # gax index of each
        # sign of sorting gax_index (inversions)
        inv = sum(1 for a in range(len(gax_index)) for b in range(a + 1, len(gax_index)) if gax_index[a] > gax_index[b])
        gmask = sum(1 << g for g in gax_index)
        return gmask, (-1) ** inv
    return to_gax

def dense_to_numga(values, space, to_gax):
    # values: dense gax coefficients -> numga layout values
    out = []
    for m, s in zip(space.masks, space.signs):
        gm, gs = to_gax(m)
        out.append(values[gm] * gs * s)
    return np.array(out)

def numga_to_dense(ext, to_gax, nblades):
    space = ext.gatype.subspaces[0] if hasattr(ext.gatype, 'subspaces') else ext.subspace
    vals = np.asarray(ext.kernel)
    d = np.zeros(nblades)
    for v, m, s in zip(vals, space.masks, space.signs):
        gm, gs = to_gax(m)
        d[gm] += v * s * gs
    return d

def export(ga, n_euclid, path, rng):
    to_gax = mapping(n_euclid)
    nb = 1 << (n_euclid + 1)
    mv = NumpyContext(ga).multivector
    full = ga.subspace.full()
    lines = []
    for trial in range(12):
        a = rng.uniform(-1, 1, nb)
        b = rng.uniform(-1, 1, nb)
        A = mv.full(dense_to_numga(a, full, to_gax))
        B = mv.full(dense_to_numga(b, full, to_gax))
        ops = {
            'gp': A * B,
            'wedge': A ^ B,
            'vee': A & B,
            'dot': A | B,
            'commutator': A.commutator(B),
            'reverse': A.reverse(),
            'dual': A.dual(),
        }
        for name, r in ops.items():
            d = numga_to_dense(r, to_gax, nb)
            lines.append(' '.join([name] + [repr(float(x)) for x in np.concatenate([a, b, d])]))
    with open(path, 'w') as f:
        f.write('# op a[0..n] b[0..n] result[0..n]: dense coefficients in gax canonical blade order\n')
        f.write('# generated by docs/research/experiments/numga_fixtures.py from numga ' + '71779db' + '\n')
        f.write('\n'.join(lines) + '\n')

rng = np.random.default_rng(7)
